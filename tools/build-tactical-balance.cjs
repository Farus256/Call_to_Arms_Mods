// Explicit offline resource build; never writes into the installed game.
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const sdl=require('./lib/sdl.cjs'),cfg=require('./tactical-balance.json');
const repo=path.resolve(__dirname,'..');
const sources=path.resolve(process.argv[2]||path.join(repo,'../_survival_work/system-effective'));
const target=path.join(repo,'mods/ultimate_frontline_bundle/resource');
const backup=path.join(repo,'../_survival_work/tactical-before');
const manifest=[];
assert(sources!==target,'Use the preserved source snapshot, not the generated resources');
function read(rel){return fs.readFileSync(path.join(sources,rel),'utf8');}
function save(rel,text){
 sdl.parse(text);const dest=path.join(target,rel),old=path.join(backup,rel);
 if(fs.existsSync(dest)&&!fs.existsSync(old)){fs.mkdirSync(path.dirname(old),{recursive:true});fs.copyFileSync(dest,old);}
 fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,text);
 manifest.push(rel);
}
function edit(text,nodes,fn){for(const n of nodes.sort((a,b)=>b.start-a.start))text=text.slice(0,n.start)+fn(n)+text.slice(n.end);return text;}
function walk(d){return fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(d,e.name)):[path.join(d,e.name)]);}
assert(Number.isFinite(cfg.baseHealth)&&cfg.baseHealth>0&&Number.isFinite(cfg.maximumBreedHealthMultiplier)&&cfg.maximumBreedHealthMultiplier>=1);
assert(Number.isFinite(cfg.healthTierCompression)&&cfg.healthTierCompression>=0&&cfg.healthTierCompression<=1);
assert(Number.isFinite(cfg.regenerationPerSecond)&&cfg.regenerationPerSecond>=0);
assert(Number.isFinite(cfg.advanceRatio)&&cfg.advanceRatio>=0);
for(const value of Object.values(cfg.supplyRadius))assert(Number.isFinite(value)&&value>0);
for(const row of Object.values(cfg.rotationDegreesPerSecond))for(const value of Object.values(row))assert(Number.isFinite(value)&&value>0);
let human=read('properties/human.ext'),ast=sdl.parse(human);
const health=sdl.child(ast.children.find(n=>sdl.name(n)==='extender'&&n.tokens[1]?.value==='vitality'),'Health');
assert(health.children.every(n=>['max','current','inc','mod'].includes(sdl.name(n))),'Unexpected Health property; review before replacing');
assert(health.children.filter(n=>sdl.name(n)==='mod').every(n=>n.children.every(c=>sdl.name(c)==='inc')),'Unexpected Health override; review before replacing');
if(cfg.enabled.health)human=edit(human,[health],()=>`{Health\n\t\t{max ${cfg.baseHealth}}\n\t\t{current ${cfg.baseHealth}}\n\t\t{inc ${cfg.regenerationPerSecond}} ; regeneration per second, before breed modifiers\n\t}`);
// All autonomous human actors inherit a cautious baseline, including story maps.
if(cfg.enabled.cautiousAdvance){
 const brain=sdl.parse(human).children.find(n=>sdl.name(n)==='brain'&&n.tokens[1]?.value==='human');
 const advance=sdl.child(sdl.child(brain,'Properties'),'advance_ratio');assert(advance);
 human=edit(human,[advance],()=>`{advance_ratio ${cfg.advanceRatio}}`);
}
if(cfg.enabled.rotation){
 const chassis=sdl.parse(human).children.find(n=>sdl.name(n)==='Chassis'&&n.tokens[1]?.value==='foot');
 const changes=[];
 for(const [posture,modes] of Object.entries(cfg.rotationDegreesPerSecond)){
  const block=sdl.child(chassis,posture);assert(block);
  for(const n of block.children){
   if(modes[sdl.name(n)]!==undefined){assert(n.tokens.length===4);changes.push({...n,replacement:`{${n.tokens[0].value} ${n.tokens[1].value} ${n.tokens[2].value} ${modes[sdl.name(n)]}}`});}
   else if(sdl.name(n)==='mod'&&n.tokens[1]?.value.startsWith('gametype:')){
    assert(n.children.every(c=>modes[sdl.name(c)]!==undefined),'Unknown rotation override');
    changes.push({...n,replacement:''});
   }
  }
 }
 human=edit(human,changes,n=>n.replacement).replaceAll('; UFB: limit heading changes outside story; movement and animation speeds stay intact.','; UFB: turn rate follows movement mode; translation and animation speeds are unchanged.');
 human=human.replace(/^([ \t]*\{(?:Sneak|Slow|Normal) [^\r\n]*?)[ \t]+(\r?)$/gm,'$1$2');
}
save('properties/human.ext',human);
// Change the HEALTH ability table only: other percentage abilities keep their scale.
const levels=sdl.all(sdl.parse(read('set/ability/level_generic.inc')),n=>sdl.name(n)==='level');
assert(levels.length>100);
save('set/ability/health.set',cfg.enabled.health?'; UFB: generated by tools/build-tactical-balance.cjs. All game modes.\n{health\n'+levels.map(n=>{
 const original=Number(n.tokens[2].value);
 const factor=original<=1?original:Math.min(cfg.maximumBreedHealthMultiplier,1+(original-1)*cfg.healthTierCompression);
 return `    {level "${n.tokens[1].value}" ${Number(factor.toFixed(6))}}`;
}).join('\n')+'\n}\n':read('set/ability/health.set'));
// Experience grants skills/stamina, no extra biological hit points.
let vet=read('set/ability/veterancy.set');
if(cfg.enabled.health)vet=edit(vet,sdl.all(sdl.parse(vet),n=>sdl.name(n)==='health'),()=>'{"health" 0}');
save('set/ability/veterancy.set',vet);
let supply=read('properties/resupply.inc');
const defs=sdl.parse(supply).children.filter(n=>sdl.name(n)==='define'&&cfg.supplyRadius[n.tokens[1]?.value]);
assert.equal(defs.length,Object.keys(cfg.supplyRadius).length);
const replacements=[];
for(const def of defs){const radius=sdl.child(sdl.child(def,'extender'),'radius');assert(radius);replacements.push({...radius,value:cfg.supplyRadius[def.tokens[1].value]});}
if(cfg.enabled.supply)supply=edit(supply,replacements,n=>`{radius ${n.value}}`);save('properties/resupply.inc',supply);
// Soft vehicles: try an available machine gun before spending grenades/rockets.
// Armored target classes retain their existing AP/volume-specific rules.
let ammo=read('set/target/ammo.set');
if(cfg.enabled.softVehicleFire){
 const car=sdl.all(sdl.parse(ammo),n=>sdl.name(n)==='car')[0];assert(car);
 const rocket=car.children.find(n=>sdl.name(n)==='ammo rocketlauncher');assert(rocket);
 ammo=ammo.slice(0,rocket.start)+'; UFB: MG fire at vulnerable soft-vehicle volumes before consumable AT weapons.\n\t\t{"mgun" {volume "engine"}}\n\t\t{"mgun" {volume "body"}}\n\t\t'+ammo.slice(rocket.start);
}
save('set/target/ammo.set',ammo);
// Only CP factors of bots. MP, income and role-specific human budgets are retained.
let cpFactors=0;
for(const file of walk(path.join(sources,'set/multiplayer/games/presets'))){
 const rel=path.relative(sources,file).replaceAll('\\','/'),text=read(rel);
 if(!/bots[^/]*\.inc$/.test(rel))continue;
 const factors=sdl.all(sdl.parse(text),n=>sdl.name(n)==='balancingFactorBonus').flatMap(n=>n.children.filter(c=>sdl.name(c)==='cp'));
 if(!factors.length)continue;
 assert(factors.every(n=>Number.isFinite(Number(n.tokens[1].value))));
 cpFactors+=factors.length;save(rel,cfg.enabled.botCP?edit(text,factors,()=>'{cp 1.0}'):text);
}
const report={source:sources,enabled:cfg.enabled,baseHealth:cfg.baseHealth,healthLevels:levels.length,cpFactors,files:manifest};
fs.mkdirSync(path.join(repo,'docs/realism/tactical'),{recursive:true});
fs.writeFileSync(path.join(repo,'docs/realism/tactical/build.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
